import {build} from 'esbuild';
import {readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
/** Produce the same synthetic Adapter for a workspace-free embedded test host. */
const root=resolve(import.meta.dirname,'../..');
const result=await build({absWorkingDir:root,entryPoints:['apps/playground/fixtures/key-office-filter/gateway.ts'],bundle:true,write:false,format:'esm',platform:'browser'});
const target=resolve(root,'packages/embed/tests/fixtures/key-office-filter.mjs');
const source='// Generated by tools/scripts/key-office-fixture.mjs; edit the TypeScript sources.\n'+result.outputFiles[0].text;
if(process.argv.includes('--check')){
 if(await readFile(target,'utf8')!==source)throw Error('Synthetic key-office Adapter is stale');
}else await writeFile(target,source);
