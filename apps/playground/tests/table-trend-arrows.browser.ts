import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { expect, test } from '@playwright/test';
const require = createRequire(import.meta.url);
const ExcelJS = createRequire(require.resolve('@metriccanvas/engine/ui'))('exceljs');
const fixture = JSON.parse(readFileSync(new URL('../../../pages/capabilities/table/table-trend-arrows.json', import.meta.url), 'utf8'));

test('table arrows share precision and units while staying independent of colors and export values', async ({ page }, info) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto(`/pages/${fixture.id}`);
  const table = page.locator('[data-component="main/trend-table"]');
  const rows = table.locator('tbody tr');
  const growth = rows.locator('[data-column-field="growth"]');
  const cost = rows.locator('[data-column-field="cost"]');
  await expect(growth).toHaveText(['↑ +2.5 万元', '↓ -1.2 万元', '0 万元', '--', '0 万元', '0 万元', '↑ +0.1 万元', '↓ -0.1 万元']);
  await expect(cost.first()).toHaveText('+2.5 天 ↓');
  await expect(cost.nth(1)).toHaveText('-1.2 天 ↑');
  await expect(cost.first().getByLabel('下箭头')).toHaveText('↓');
  await expect(cost.nth(1).getByLabel('上箭头')).toHaveText('↑');
  await expect(growth.first()).toHaveCSS('color', 'rgb(82, 196, 26)');
  await expect(cost.first()).toHaveCSS('color', 'rgb(245, 34, 45)');
  await expect(growth.nth(1)).toHaveCSS('color', 'rgb(245, 34, 45)');
  await expect(cost.nth(1)).toHaveCSS('color', 'rgb(82, 196, 26)');
  await expect(growth.first().getByLabel('上箭头')).toHaveText('↑');
  await expect(growth.nth(1).getByLabel('下箭头')).toHaveText('↓');
  await expect(rows.locator('[data-column-field="off"] .cell-trend-arrow')).toHaveCount(0);
  await expect(rows.locator('[data-column-field="legacy"] .cell-trend-arrow')).toHaveCount(0);
  await expect(rows.locator('[data-column-field="enum"]').first()).toHaveText('已达标');
  await expect(rows.locator('[data-column-field="tiny"]').first()).toHaveText('+2.5 天');
  const rate = rows.locator('[data-column-field="rate"]').nth(1);
  await expect(rate).toHaveText('-1.2% ↓');
  await expect(rows.locator('[data-column-field="rate"]').first()).toHaveText('+2.5% ↓');
  await expect(rows.locator('[data-column-field="rate"]').nth(2)).toHaveText('0% ↓');
  await expect(rows.locator('[data-column-field="rate"]').nth(3)).toHaveText('--');
  await expect(rows.locator('[data-column-field="tiny"]').nth(1)).toHaveText('↓ -1.2 天');
  await expect(rate).toHaveCSS('color', 'rgb(82, 196, 26)');
  await expect(page.locator('[data-component="variants/compact-trend-table"] .cell-trend-arrow')).toHaveCount(4);
  await expect(page.locator('[data-component="variants/compact-trend-table"] td[data-column-field="growth"]').first()).toHaveText('↓ +2.5 天');
  await expect(page.locator('[data-component="variants/rate-trend-table"] .rate-cell .cell-trend-arrow')).toHaveCount(7);
  await expect(page.locator('[data-component="variants/rate-trend-table"] td[data-column-field="cost"]').first()).toHaveText('↑ +2.5 天');
  const download = page.waitForEvent('download');
  await table.getByRole('button', { name: '导出', exact: true }).click();
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.readFile((await (await download).path())!);
  const sheet = workbook.worksheets[0];
  expect(sheet.getCell('B3').value).toBe(2.5);
  expect(sheet.getCell('B3').numFmt).toMatch(/^"↑ /);
  expect(sheet.getCell('C4').value).toBe(-1.2);
  expect(sheet.getCell('C4').numFmt).toContain('↑');
  expect(sheet.getCell('C3').numFmt).toMatch(/ ↓"$/);
  expect(sheet.getCell('D5').value).toBe(0);
  expect(sheet.getCell('D5').numFmt).toContain('↓');
  expect(sheet.getCell('B5').value).toBe(0);
  expect(sheet.getCell('B5').numFmt).not.toMatch(/[↑↓]/);
  expect(sheet.getCell('B6').value).toBeNull();
  await page.screenshot({ path: info.outputPath('table-arrows-wide.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(growth.first()).toHaveText('↑ +2.5 万元');
  await expect(growth.first().getByLabel('上箭头')).toBeVisible();
  await page.screenshot({ path: info.outputPath('table-arrows-narrow.png'), fullPage: true });
  expect(errors).toEqual([]);
});
