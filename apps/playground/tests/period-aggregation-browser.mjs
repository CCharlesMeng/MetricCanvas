import { chromium, expect as baseExpect } from '../../../packages/embed/node_modules/@playwright/test/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';

const require = createRequire(new URL('../../../packages/engine/package.json', import.meta.url));
const ExcelJS = require('exceljs');
const base = process.env.PLAYGROUND_BASE_URL ?? 'http://127.0.0.1:5276';
const output = process.argv[2] ?? '/tmp/mc-period-aggregation';
const expect = baseExpect.configure({ timeout: 30_000 });
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
page.setDefaultTimeout(30_000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const table = page.locator('[data-component="efficiency/efficiency-table"]');
const chart = page.locator('[data-component="efficiency/efficiency-chart"]');
try {
  await page.clock.install({ time: new Date('2026-11-07T04:00:00Z') });
  await page.goto(`${base}/pages/sdt-period-aggregation`);
  const rows = table.locator('tbody tr');
  await expect(rows).toHaveCount(2);
  await expect(rows.first()).toContainText('合成代表处甲');
  await expect(rows.first()).toContainText('120');
  await expect(rows.first()).toContainText('6.5');
  const canvas = chart.locator('canvas').first();
  await expect(canvas).toBeVisible();
  const box = await canvas.boundingBox();
  await canvas.hover({ position: { x: box.width / 4, y: box.height / 2 } });
  await expect(chart).toContainText('120');
  await expect(chart).toContainText('6.5');
  await page.mouse.move(0, 0);
  await table.getByRole('button', { name: '下一页', exact: true }).click();
  await expect(rows).toHaveCount(1);
  await expect(rows.first()).toContainText('合成代表处丙');
  await expect(rows.first()).toContainText('--');
  const downloading = page.waitForEvent('download');
  await table.getByRole('button', { name: '导出', exact: true }).click();
  const filename = path.join(output, 'annual.xlsx');
  await (await downloading).saveAs(filename);
  const book = new ExcelJS.Workbook();
  await book.xlsx.readFile(filename);
  const sheet = book.worksheets[0];
  expect(sheet.rowCount).toBe(4);
  expect(sheet.getCell('B2').value).toBe(120);
  expect(sheet.getCell('C2').value).toBe(6.5);
  await page.getByRole('button', { name: '月', exact: true }).click();
  await expect(rows.filter({ hasText: '合成代表处甲' })).toContainText('10');
  await expect(table).not.toContainText('120');
  await page.getByRole('button', { name: '近一年', exact: true }).click();
  await expect(rows.filter({ hasText: '合成代表处甲' })).toContainText('120');
  await page.clock.runFor(1500);
  await page.screenshot({ path: path.join(output, 'annual.png'), fullPage: true });
  await page.goto(`${base}/pages/sdt-period-aggregation?state=truncated`);
  await expect(table.getByRole('columnheader', { name: '代表处', exact: true })).toBeVisible();
  await expect(table).not.toContainText('合成代表处甲');
  await expect(table).not.toContainText('正在加载');
  expect(errors).toEqual([]);
  await writeFile(path.join(output, 'result.json'), JSON.stringify({ checks: ['sum/avg table and chart tooltip', 'null and pagination', 'complete XLSX values', 'month switch and restore', 'incomplete month rejected'], errors }, null, 2));
  console.log('Period aggregation browser acceptance passed');
} finally { await browser.close(); }
