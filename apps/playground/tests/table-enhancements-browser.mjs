import { chromium, expect } from '../../../packages/embed/node_modules/@playwright/test/index.mjs';
import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import ExcelJS from '../../../packages/engine/node_modules/exceljs/excel.js';

const base = process.env.PLAYGROUND_BASE_URL ?? 'http://127.0.0.1:5180';
const output = process.argv[2] ?? '/tmp/metriccanvas-table-enhancements';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {
    if (request.method() === 'POST' && request.url().endsWith('/dsl/execute')) requests.push(...JSON.parse(request.postData()).dsl_list);
  });
  await page.goto(base + '/pages/table-value-tolerance');
  let table = page.locator('[data-component="main/records"]');
  await expect(table.locator('tbody')).toContainText('2026-09 ~ 2026-10');
  await expect(table.locator('tbody')).toContainText('待确认');
  await expect(table.locator('tbody')).toContainText('123');
  const download = page.waitForEvent('download');
  await table.getByRole('button', {name:'导出',exact:true}).click();
  const file = await download;
  const filename = path.join(output, 'tolerance.xlsx');
  await file.saveAs(filename);
  const workbook = new ExcelJS.Workbook(); await workbook.xlsx.readFile(filename);
  expect(workbook.worksheets[0].getCell('C3').value).toBe('2026-09 ~ 2026-10');
  expect(workbook.worksheets[0].getCell('E3').value).toBe('待确认');
  await page.screenshot({path:path.join(output,'tolerance.png'),fullPage:true});

  await page.goto(base + '/pages/table-missing-sort');
  table = page.locator('[data-component="main/records"]');
  const sort = table.locator('th[data-column-field="value"] button').first();
  await expect(table.locator('tbody tr')).toHaveCount(8);
  await sort.click();
  await expect(table.locator('tbody tr').first()).toContainText('负数');
  await expect(table.locator('tbody tr').last()).toContainText('长横杠');
  await sort.click();
  await expect(table.locator('tbody tr').first()).toContainText('正常');
  await expect(table.locator('tbody tr').last()).toContainText('长横杠');
  await page.screenshot({path:path.join(output,'missing-sort.png'),fullPage:true});

  await page.goto(base + '/pages/table-pinned-summary');
  table = page.locator('[data-component="main/regional-table"]');
  await expect(table.locator('tbody tr')).toHaveCount(3);
  await expect(table.locator('[data-pinned-top] [data-row-number]')).toHaveText('');
  await expect(table.locator('tbody tr').first()).toContainText('中国区');
  await table.getByRole('button', {name:'2',exact:true}).click();
  await expect(table.locator('tbody [data-row-number]').nth(1)).toHaveText('3');
  const summaryCount = () => requests.filter(item => item.output_dims?.includes('summary_scope')).length;
  const beforeRegion = summaryCount();
  await page.getByRole('button', {name:'地区',exact:true}).click();
  await page.getByRole('option', {name:'华东地区部',exact:true}).click();
  await expect(table.locator('tbody tr')).toHaveCount(2);
  await expect(table.locator('[data-pinned-top]')).toContainText('168万');
  expect(summaryCount()).toBe(beforeRegion);
  await page.getByRole('button', {name:'产品',exact:true}).click();
  await page.getByRole('option', {name:'高级产品',exact:true}).click();
  await expect(table.locator('[data-pinned-top]')).toContainText('504万');
  expect(summaryCount()).toBe(beforeRegion + 1);
  await page.getByRole('textbox', {name:'统计月份结束',exact:true}).fill('2026-10');
  await page.getByRole('textbox', {name:'统计月份结束',exact:true}).press('Enter');
  await page.locator('input[aria-label="统计月份开始"]').fill('2026-10');
  await page.locator('input[aria-label="统计月份开始"]').press('Enter');
  await expect(table.locator('[data-pinned-top]')).toContainText('1,008万');
  await page.screenshot({path:path.join(output,'pinned-summary.png'),fullPage:true});
  await page.getByRole('button', {name:'汇总场景',exact:true}).click();
  await page.getByRole('option', {name:'多行',exact:true}).click();
  await expect(table.locator('[data-pinned-top]')).toHaveCount(0);
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await table.getByRole('button', {name:'导出',exact:true}).click();
  await expect(table.getByRole('alert')).toContainText('置顶');
  await page.getByRole('button', {name:'汇总场景',exact:true}).click();
  await page.getByRole('option', {name:'查询失败',exact:true}).click();
  await expect(table.locator('tbody tr')).toHaveCount(1);
  await expect(table.locator('[data-pinned-top]')).toHaveCount(0);
  await page.getByRole('button', {name:'汇总场景',exact:true}).click();
  await page.getByRole('option', {name:'正常',exact:true}).click();
  await expect(table.locator('[data-pinned-top]')).toHaveCount(1);
  await page.setViewportSize({width:390,height:844});
  await expect(table.locator('[data-pinned-top] [data-row-number]')).toHaveText('');
  await page.screenshot({path:path.join(output,'pinned-summary-mobile.png'),fullPage:true});
  expect(errors).toEqual([]);
  console.log(JSON.stringify({routes:3,errors,summaryRequests:summaryCount(),exportTextVerified:true}));
} finally { await browser.close(); }
