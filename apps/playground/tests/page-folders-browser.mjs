import { chromium, expect } from '../../../packages/embed/node_modules/@playwright/test/index.mjs';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { pageFiles } from '../../../tools/scripts/page-files.mjs';

const base = process.env.PLAYGROUND_BASE_URL ?? 'http://127.0.0.1:5173';
const output = process.argv[2] ?? '/tmp/metriccanvas-page-folders';
const pagesRoot = fileURLToPath(new URL('../../../pages/', import.meta.url));
const temporary = path.join(pagesRoot, 'business/dashboard/folder-migration-check');
const files = pageFiles(pagesRoot);
const total = files.length;
const subtreeCount = folder => files.filter(file => file.startsWith(`${folder}/`)).length;
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.setDefaultTimeout(10_000);
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const facts = {};
const folder = page.getByLabel('文件夹路径', { exact: true });

try {
  await page.goto(base);
  await expect(page.locator('.page-card')).toHaveCount(total);
  await folder.selectOption('business/report');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('business/report'));
  await expect(page.locator('.layout-badge.dashboard')).toHaveCount(0);
  await folder.selectOption('business/dashboard/ioc');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('business/dashboard/ioc'));
  await folder.selectOption('business/dashboard/ioc/project');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('business/dashboard/ioc/project'));
  await expect(page.locator('.groups')).toContainText('business/dashboard/ioc/project/');
  await page.screenshot({ path: path.join(output, 'ioc-project.png'), fullPage: true });
  facts.businessHierarchy = true;

  await page.locator('.page-card[href="/pages/ioc-project-detail"]').click();
  await expect(page).toHaveURL(`${base}/pages/ioc-project-detail`);
  await page.getByRole('link', { name: '← 页面目录' }).click();
  await expect(folder).toHaveValue('business/dashboard/ioc/project');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('business/dashboard/ioc/project'));
  await page.reload();
  await expect(folder).toHaveValue('business/dashboard/ioc/project');
  facts.returnAndReload = true;

  await folder.selectOption('capabilities/table');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('capabilities/table'));
  await page.getByRole('searchbox', { name: '搜索页面', exact: true }).fill('table-detail-overlay');
  await expect(page.locator('.page-card')).toHaveCount(1);
  const card = page.locator('.page-card[href="/pages/table-detail-overlay"]');
  await card.scrollIntoViewIfNeeded();
  const scrollY = await page.evaluate(() => scrollY);
  await card.click();
  await expect(page).toHaveURL(`${base}/pages/table-detail-overlay`);
  await expect(page.getByRole('complementary', { name: '页面 JSON' })).toBeVisible();
  await page.goBack();
  await expect(folder).toHaveValue('capabilities/table');
  await expect(page.getByRole('searchbox')).toHaveValue('table-detail-overlay');
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBeCloseTo(scrollY, 0);
  facts.combinedFilterAndScroll = true;
  await page.getByRole('searchbox').fill('无匹配目录页面');
  await expect(page.getByRole('heading', { name: '没有找到匹配页面' })).toBeVisible();
  await page.locator('.empty').getByRole('button', { name: '重置筛选' }).click();
  await expect(folder).toHaveValue('all');
  await expect(page.locator('.page-card')).toHaveCount(total);
  await page.getByRole('searchbox').fill('business/dashboard/ioc/opportunity');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('business/dashboard/ioc/opportunity'));
  await page.getByRole('searchbox').fill('');
  await expect(page.locator('.page-card')).toHaveCount(total);
  facts.pathSearchAndReset = true;

  const document = JSON.parse(await readFile(path.join(pagesRoot, 'capabilities/layout/demo.json'), 'utf8'));
  document.id = 'folder-migration-observable';
  document.layout = 'dashboard';
  document.meta = { ...document.meta, description: '目录热更新第一版' };
  await mkdir(temporary);
  await writeFile(path.join(temporary, `${document.id}.json`), JSON.stringify(document));
  await expect(folder.locator('option[value="business/dashboard/folder-migration-check"]')).toHaveCount(1);
  await folder.selectOption('business/dashboard/folder-migration-check');
  await expect(page.locator('.page-card')).toHaveCount(1);
  await expect(page.locator('.page-card')).toContainText('目录热更新第一版');
  await page.getByRole('navigation', { name: '布局形态' }).getByRole('button', { name: /^Dashboard/ }).click();
  await expect(page.locator('.page-card')).toHaveCount(1);
  await page.screenshot({ path: path.join(output, 'unregistered-business-module.png'), fullPage: true });
  await page.locator('.page-card').click();
  await expect(page).toHaveURL(`${base}/pages/${document.id}`);
  await expect(page.locator('.page-frame .page-sections').first()).toBeVisible();
  await expect(page.locator('.error-page')).toHaveCount(0);
  await page.getByRole('link', { name: '← 页面目录' }).click();
  await expect(folder).toHaveValue('business/dashboard/folder-migration-check');
  await expect(page.locator('.page-card')).toHaveCount(1);
  facts.automaticBusinessModule = true;
  document.meta.description = '目录热更新第二版';
  await writeFile(path.join(temporary, `${document.id}.json`), JSON.stringify(document));
  await expect(page.locator('.page-card')).toContainText('目录热更新第二版');
  await rm(temporary, { recursive: true });
  await expect(folder).toHaveValue('all');
  await page.getByRole('button', { name: '重置筛选', exact: true }).first().click();
  await expect(page.locator('.page-card')).toHaveCount(total);
  await expect(folder.locator('option[value="business/dashboard/folder-migration-check"]')).toHaveCount(0);
  facts.addEditRemoveRefresh = true;

  await page.setViewportSize({ width: 390, height: 844 });
  await folder.selectOption('business/dashboard/ioc/opportunity');
  await expect(page.locator('.page-card')).toHaveCount(subtreeCount('business/dashboard/ioc/opportunity'));
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: path.join(output, 'folders-mobile.png'), fullPage: true });
  facts.mobile = true;
  expect(errors).toEqual([]);
  const result = { status: 'pass', ...facts, errors };
  await writeFile(path.join(output, 'result.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} catch (error) {
  console.error(JSON.stringify({ facts, url: page.url(), errors }));
  await page.screenshot({ path: path.join(output, 'failure.png'), fullPage: true });
  throw error;
} finally {
  await rm(temporary, { recursive: true, force: true });
  await browser.close();
}
