/**
 * 工作台空态的建议问题(工作台与按需验证共读这一份,不允许手抄第二份)。
 *
 * 每条问题都必须满足以下约束,否则点下去走不到「真实取数 + 可渲染文档」:
 * - 指标名、维度名与维度取值逐字取自语义面(tools/dqe-sim/src/semantic-surface.ts);
 * - 时间口径写成具体年月:相对时间由模型补全会让取数核对阻塞等确认
 *   (orchestrator 的 model_completed_time 触发条件),体验上「点一下就出页面」不成立;
 * - 一条问题只落在一个业务域:同一取数单元不能跨域组合,且跨域没有共用的非时间维度;
 * - 避开跨域同名指标的裸称「客户数」(会触发消歧阻塞),要用域内唯一的别名
 *   「在用客户数」(运营分析)/「在册客户数」(客户经营);
 * - 避开组件目录(packages/page 的 componentCatalog)的名称与别名,例如「表格」
 *   「折线图」「趋势图」「饼图」「指标卡」:那些词会被识别为显式点名组件,把展示
 *   形态写死,恰好毁掉这里想展示的「形态由数据形状决定」。
 *
 * **组件形态的多样性来自口径差异,不来自点名。** 组件由每个取数单元的结果形状
 * 与分析意图决定(packages/mcp 的 auto-visualize 硬闸 + 意图排序):不切分的总量
 * 出指标卡、按统计周期切分求走势出折线、按类别维度求对比出柱状、单指标求占比出
 * 饼图、两个维度交叉只有明细表过闸。所以同一口径的多指标问题必然产出同一种组件
 * (四个柱状图),想看真实看板那样的一整页,问题就得点到多个**切分视角**——`pages/`
 * 下既有的运营简报正是这个形状:总量 + 按统计周期 + 按区域 + 按模型。
 * 跨口径不阻塞,但差异必须一直可见,靠一个口径组一个内容分区承载(ADR-0055)。
 */
export interface SuggestedQuestion {
  question: string;
  /**
   * 空态按钮上的短标题。跨口径问题要把每个切分视角写进问题,一句就有百来字,
   * 在 292px 宽的对话轨里铺成五行;点下去问题原文立刻进提问气泡,按钮本身
   * 不必承担全文。缺省时按钮直接显示问题原文。
   */
  label?: string;
  /** 该问题应铺开的视角数下限;一个取数单元一个组件。 */
  minComponents: number;
  /**
   * 期望各自成为一个口径组(一个内容分区)的分组维度组合。给出即声明这是一条
   * 跨口径问题:各单元的结果形状不同,组件形态因此不同。缺省表示单口径问题——
   * 全部单元共用同一分组维度与时间窗口,组件之间可以横向对照。
   */
  splitBy?: ReadonlyArray<readonly string[]>;
  /**
   * 期望出现的不同组件形态数下限。只对跨口径问题声明,且只取**硬闸保证**的那部分
   * ——意图由模型判定,「占比」被判成对比就从饼图退回柱状图,数仍然是对的。
   */
  minComponentTypes?: number;
}

