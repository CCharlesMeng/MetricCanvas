import { planPdfPages } from './report-pdf-pagination';

function computedDeclarations(style: CSSStyleDeclaration): string {
  return Array.from(style).map(name => `${name}:${style.getPropertyValue(name)}`).join(';');
}

/** Preserve the prepared view's appearance when moving out of engine/shadow-root styles. */
function copyPdfView(target: HTMLElement): HTMLElement {
  const copy = target.cloneNode(true) as HTMLElement;
  const originals = [target, ...target.querySelectorAll<HTMLElement>('*')];
  const copies = [copy, ...copy.querySelectorAll<HTMLElement>('*')];
  const pseudoRules: string[] = [];
  originals.forEach((element, index) => {
    const computed = getComputedStyle(element);
    const clone = copies[index];
    clone.removeAttribute('style');
    // Freeze the complete laid-out style, including heights, alignment tracks and nested grids.
    clone.style.cssText = computedDeclarations(computed);
    // Scoped widget styles do not exist in the encoder document. Preserve decorative backgrounds
    // and text generated by pseudo-elements as computed rules scoped to this copied element.
    for (const pseudo of ['::before', '::after']) {
      const decoration = getComputedStyle(element, pseudo);
      if (decoration.content === 'none' || decoration.content === 'normal' || decoration.display === 'none') continue;
      clone.dataset.pdfElement = String(index);
      pseudoRules.push(`[data-pdf-element="${index}"]${pseudo}{${computedDeclarations(decoration)}}`);
    }
    // html2canvas does not model CSS isolation; make existing positioned isolated layers explicit.
    if (computed.isolation === 'isolate' && computed.position !== 'static' && computed.zIndex === 'auto') clone.style.zIndex = '0';
    if (element.matches('.report-header, .report-cover')) clone.style.minHeight = computed.minHeight;
    // Frozen ECharts images remain absolutely positioned; their containing block must keep its height.
    if (element.matches('[data-export-chart]')) {
      const rect = element.getBoundingClientRect();
      // Absolute images provide no intrinsic flex size in the copied document.
      const height = Math.max(rect.height, ...Array.from(element.querySelectorAll('img')).map(image => image.getBoundingClientRect().bottom - rect.top));
      clone.style.height = `${height}px`;
      clone.style.minHeight = `${height}px`;
      clone.style.flex = 'none';
    }
    // Static charts need their measured dimensions; other blocks must fragment naturally.
    if (element.tagName === 'IMG') {
      const image = element as HTMLImageElement;
      clone.setAttribute('src', image.currentSrc || image.src);
      clone.removeAttribute('srcset');
      clone.removeAttribute('sizes');
      clone.style.width = `${element.getBoundingClientRect().width}px`;
      clone.style.height = `${element.getBoundingClientRect().height}px`;
    }
    for (const attribute of Array.from(clone.attributes)) {
      if (attribute.name.startsWith('on')) clone.removeAttribute(attribute.name);
    }
  });
  if (pseudoRules.length) {
    const style = target.ownerDocument.createElement('style');
    style.textContent = pseudoRules.join('\n');
    copy.append(style);
  }
  return copy;
}

const pdfStyles = `
  html,body { margin:0; padding:0; background:white; print-color-adjust:exact; -webkit-print-color-adjust:exact; }
  * { animation:none!important; transition:none!important; }
`;

/** html2canvas cannot clip a gradient to glyphs. Freeze those small elements with native SVG/HTML paint. */
async function freezeGradientText(view: HTMLElement, signal: AbortSignal): Promise<void> {
  const document = view.ownerDocument;
  const pseudoStyles = Array.from(view.querySelectorAll('style')).map(style => style.textContent).join('\n');
  const gradients = [view, ...view.querySelectorAll<HTMLElement>('*')].filter(element => {
    const style = getComputedStyle(element);
    return style.backgroundImage.includes('gradient(') && (style.backgroundClip === 'text' || style.getPropertyValue('-webkit-background-clip') === 'text');
  });
  // Rasterise parents first; descendants they already contain need no second overlay.
  for (const element of gradients.filter(element => !gradients.some(parent => parent !== element && parent.contains(element)))) {
    signal.throwIfAborted();
    const rect = element.getBoundingClientRect();
    if (!rect.width || !rect.height) continue;
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('width', String(rect.width * 2));
    svg.setAttribute('height', String(rect.height * 2));
    svg.setAttribute('viewBox', `0 0 ${rect.width} ${rect.height}`);
    const foreign = document.createElementNS(svg.namespaceURI, 'foreignObject');
    foreign.setAttribute('width', String(rect.width));
    foreign.setAttribute('height', String(rect.height));
    const wrapper = document.createElement('div');
    const rules = document.createElement('style');
    rules.textContent = pseudoStyles;
    const copy = element.cloneNode(true) as HTMLElement;
    copy.style.margin = '0';
    copy.style.position = 'static';
    copy.style.transform = 'none';
    copy.style.width = `${rect.width}px`;
    copy.style.height = `${rect.height}px`;
    wrapper.append(rules, copy);
    foreign.append(wrapper);
    svg.append(foreign);
    const image = document.createElement('img');
    image.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(new XMLSerializer().serializeToString(svg));
    await abortable(image.decode(), signal);
    signal.throwIfAborted();
    const canvas = document.createElement('canvas');
    canvas.width = Math.ceil(rect.width * 2);
    canvas.height = Math.ceil(rect.height * 2);
    const context = canvas.getContext('2d');
    if (!context) throw new Error('无法绘制渐变文字');
    let url: string;
    try {
      context.drawImage(image, 0, 0);
      url = canvas.toDataURL('image/png');
      signal.throwIfAborted();
    } finally { canvas.width = 0; canvas.height = 0; }
    element.style.position = 'relative';
    element.style.backgroundImage = 'none';
    element.style.color = 'transparent';
    element.style.setProperty('-webkit-text-fill-color', 'transparent');
    for (const child of element.querySelectorAll<HTMLElement>('*')) child.style.visibility = 'hidden';
    if (element.dataset.pdfElement !== undefined) {
      const hide = document.createElement('style');
      hide.textContent = `[data-pdf-element="${element.dataset.pdfElement}"]::before,[data-pdf-element="${element.dataset.pdfElement}"]::after{content:none!important}`;
      view.append(hide);
    }
    const frozen = document.createElement('img');
    frozen.src = url;
    frozen.alt = element.textContent ?? '';
    frozen.dataset.pdfGradientText = '';
    frozen.style.cssText = `position:absolute;left:0;top:0;width:${rect.width}px;height:${rect.height}px;max-width:none;visibility:visible;`;
    element.append(frozen);
    await abortable(frozen.decode(), signal);
  }
}

/** Browser-only image PDF. All pages must succeed before initiating a download. */
export async function downloadReportPdf(target: HTMLElement, signal: AbortSignal, filename = '经营分析报告.pdf'): Promise<{ pageCount: number }> {
  signal.throwIfAborted();
  const pageWidth = target.getBoundingClientRect().width;
  const landscape = !!target.querySelector('[data-export-orientation="landscape"]');
  const paperWidth = landscape ? 297 : 210;
  const paperHeight = landscape ? 210 : 297;
  const pageHeight = Math.floor(pageWidth * paperHeight / paperWidth);
  if (!Number.isFinite(pageWidth) || pageWidth <= 0) throw new Error('报告尺寸无效，无法生成 PDF');
  const [{ default: html2canvas }, { jsPDF }] = await Promise.all([import('html2canvas'), import('jspdf')]);
  signal.throwIfAborted();
  const owner = target.ownerDocument;
  const document = owner.implementation.createHTMLDocument('报告 PDF 编码视图');
  document.documentElement.lang = owner.documentElement.lang || 'zh-CN';
  const charset = document.createElement('meta');
  charset.setAttribute('charset', 'utf-8');
  const style = document.createElement('style');
  style.textContent = pdfStyles;
  const base = document.createElement('base');
  base.href = owner.baseURI;
  document.head.prepend(charset, base);
  document.head.append(style);
  document.body.append(copyPdfView(target));

  const frame = owner.createElement('iframe');
  frame.dataset.reportPdfFrame = '';
  frame.title = '报告 PDF 编码视图';
  frame.setAttribute('aria-hidden', 'true');
  frame.tabIndex = -1;
  frame.setAttribute('sandbox', 'allow-same-origin');
  frame.style.cssText = `position:fixed;left:-100000px;top:0;width:${pageWidth}px;height:${pageHeight}px;border:0;`;

  try {
    const loaded = new Promise<void>(resolve => frame.addEventListener('load', () => resolve(), { once: true }));
    frame.srcdoc = '<!doctype html>' + document.documentElement.outerHTML;
    owner.body.append(frame);
    await abortable(loaded, signal);
    const view = frame.contentDocument?.querySelector<HTMLElement>('[data-export-view]');
    if (!view) throw new Error('无法创建报告 PDF 编码视图');
    await abortable(view.ownerDocument.fonts.ready, signal);
    await abortable(Promise.all(Array.from(view.querySelectorAll('img')).map(image => image.decode())), signal);
    await freezeGradientText(view, signal);
    signal.throwIfAborted();
    const origin = view.getBoundingClientRect();
    const height = Math.ceil(origin.height);
    // Preserve the prepared layout exactly. Paper boundaries never move DOM blocks or add rows.
    const pages = planPdfPages(height, pageHeight);
    const pdf = new jsPDF({ unit: 'mm', format: 'a4', orientation: landscape ? 'landscape' : 'portrait', compress: true });
    const capturePageHeight = Math.min(height, pageHeight);
    const scale = Math.min(2, 8192 / pageWidth, 8192 / capturePageHeight, Math.sqrt(16_777_216 / (Math.ceil(pageWidth) * capturePageHeight)));
    // Render several pages together when safe: html2canvas reparses the entire DOM per call.
    // Bound both dimensions and area so long reports never allocate a report-sized canvas.
    const maxCaptureHeight = Math.floor(Math.min(8192 / scale, 16_777_216 / (Math.ceil(pageWidth * scale) * scale)));
    const options = { scale, backgroundColor: '#ffffff', logging: false, scrollX: 0, scrollY: 0, windowWidth: pageWidth, windowHeight: pageHeight };
    for (let first = 0; first < pages.length;) {
      signal.throwIfAborted();
      let last = first;
      while (last + 1 < pages.length && pages[last + 1].bottom - pages[first].top <= maxCaptureHeight) last++;
      // html2canvas cannot abort an active render. Keep its document alive until it finishes.
      const canvas = await html2canvas(view, { ...options, y: pages[first].top, width: pageWidth, height: pages[last].bottom - pages[first].top });
      const slice = owner.createElement('canvas');
      try {
        signal.throwIfAborted();
        for (let index = first; index <= last; index++) {
          const page = pages[index];
          if (index) pdf.addPage();
          slice.width = canvas.width;
          const sourceTop = Math.floor((page.top - pages[first].top) * scale);
          const sourceBottom = Math.floor((page.bottom - pages[first].top) * scale);
          slice.height = Math.max(1, sourceBottom - sourceTop);
          const context = slice.getContext('2d');
          if (!context) throw new Error('无法绘制报告 PDF');
          context.drawImage(canvas, 0, sourceTop, canvas.width, slice.height, 0, 0, canvas.width, slice.height);
          // FAST avoids jsPDF's default slow PNG recompression while retaining lossless text.
          pdf.addImage(slice.toDataURL('image/png'), 'PNG', 0, 0, paperWidth, index < pages.length - 1 ? paperHeight : (page.bottom - page.top) * paperWidth / pageWidth, undefined, 'FAST');
          signal.throwIfAborted();
        }
      } finally { canvas.width = 0; canvas.height = 0; slice.width = 0; slice.height = 0; }
      first = last + 1;
      await new Promise(resolve => setTimeout(resolve, 0));
    }
    signal.throwIfAborted();
    const url = URL.createObjectURL(pdf.output('blob'));
    try {
      const link = owner.createElement('a');
      link.href = url;
      link.download = filename;
      link.style.display = 'none';
      owner.body.append(link);
      try { link.click(); } finally { link.remove(); }
    } finally {
      // Keep the Blob alive long enough for the browser to begin reading the download.
      setTimeout(() => URL.revokeObjectURL(url), 30_000);
    }
    return { pageCount: pages.length };
  } finally { frame.remove(); }
}

function abortable<T>(work: Promise<T>, signal: AbortSignal): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const abort = () => reject(signal.reason ?? new DOMException('PDF 导出已取消', 'AbortError'));
    signal.addEventListener('abort', abort, { once: true });
    if (signal.aborted) abort();
    work.then(resolve, reject).finally(() => signal.removeEventListener('abort', abort));
  });
}
