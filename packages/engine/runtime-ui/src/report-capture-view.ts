function computedDeclarations(style: CSSStyleDeclaration): string {
  return Array.from(style).map(name => `${name}:${style.getPropertyValue(name)}`).join(';');
}

/** Preserve the prepared view's appearance when moving out of engine/shadow-root styles. */
export async function copyPdfView(target: HTMLElement, pause: () => Promise<void> | undefined): Promise<HTMLElement> {
  const copy = target.cloneNode(true) as HTMLElement;
  const originals = [target, ...target.querySelectorAll<HTMLElement>('*')];
  const copies = [copy, ...copy.querySelectorAll<HTMLElement>('*')];
  const pseudoRules: string[] = [];
  const styles = new Map<string,number>();
  for (let index = 0; index < originals.length; index++) {
    const pending = pause(); if (pending) await pending;
    const element = originals[index];
    const computed = getComputedStyle(element);
    const clone = copies[index];
    clone.removeAttribute('style');
    // Freeze the complete laid-out style, including heights, alignment tracks and nested grids.
    const declarations=computedDeclarations(computed);
    let styleId=styles.get(declarations);
    if(styleId===undefined){styleId=styles.size;styles.set(declarations,styleId);}
    clone.dataset.pdfStyle=String(styleId);
    // Scoped widget styles do not exist in the encoder document. Preserve decorative backgrounds
    // and text generated by pseudo-elements as computed rules scoped to this copied element.
    for (const pseudo of ['::before', '::after']) {
      const decoration = getComputedStyle(element, pseudo);
      if (decoration.content === 'none' || decoration.content === 'normal' || decoration.display === 'none') continue;
      clone.dataset.pdfElement = String(index);
      pseudoRules.push(`[data-pdf-element="${index}"]${pseudo}{${computedDeclarations(decoration)}}`);
    }
    // html2canvas does not model CSS isolation; make existing positioned isolated layers explicit.
    if (computed.isolation === 'isolate' && computed.position !== 'static' && computed.zIndex === 'auto') clone.style.zIndex = '0';
    if (element.matches('.report-header, .report-cover')) clone.style.minHeight = computed.minHeight;
    // Frozen ECharts images remain absolutely positioned; their containing block must keep its height.
    if (element.matches('[data-export-chart]')) {
      const rect = element.getBoundingClientRect();
      // Absolute images provide no intrinsic flex size in the copied document.
      const height = Math.max(rect.height, ...Array.from(element.querySelectorAll('img')).map(image => image.getBoundingClientRect().bottom - rect.top));
      clone.style.height = `${height}px`;
      clone.style.minHeight = `${height}px`;
      clone.style.flex = 'none';
    }
    // Static charts need their measured dimensions; other blocks must fragment naturally.
    if (element.tagName === 'IMG') {
      const image = element as HTMLImageElement;
      clone.setAttribute('src', image.currentSrc || image.src);
      clone.removeAttribute('srcset');
      clone.removeAttribute('sizes');
      clone.style.width = `${element.getBoundingClientRect().width}px`;
      clone.style.height = `${element.getBoundingClientRect().height}px`;
    }
    for (const attribute of Array.from(clone.attributes)) {
      if (attribute.name.startsWith('on')) clone.removeAttribute(attribute.name);
    }
  }
  const frozenStyles = target.ownerDocument.createElement('style');
  frozenStyles.dataset.pdfComputed = '';
  frozenStyles.textContent = [...styles].map(([declarations,id])=>`[data-pdf-style="${id}"]{${declarations}}`).join('\n');
  copy.append(frozenStyles);
  if (pseudoRules.length) {
    const style = target.ownerDocument.createElement('style');
    style.textContent = pseudoRules.join('\n');
    copy.append(style);
  }
  return copy;
}

export const pdfStyles = `
  html,body { margin:0; padding:0; background:white; print-color-adjust:exact; -webkit-print-color-adjust:exact; }
  * { animation:none!important; transition:none!important; }
`;

/** html2canvas cannot clip a gradient to glyphs. Freeze those small elements with native SVG/HTML paint. */
export async function freezeGradientText(view: HTMLElement, signal: AbortSignal, pause: () => Promise<void> | undefined, scale = 2): Promise<void> {
  const document = view.ownerDocument;
  const pseudoStyles = Array.from(view.querySelectorAll('style:not([data-pdf-computed])')).map(style => style.textContent).join('\n');
  const gradients: HTMLElement[] = [];
  for (const element of [view, ...view.querySelectorAll<HTMLElement>('*')]) {
    const pending = pause(); if (pending) await pending;
    const style = getComputedStyle(element);
    if (style.backgroundImage.includes('gradient(') && (style.backgroundClip === 'text' || style.getPropertyValue('-webkit-background-clip') === 'text')) gradients.push(element);
  }
  // Rasterise parents first; descendants they already contain need no second overlay.
  for (const element of gradients.filter(element => !gradients.some(parent => parent !== element && parent.contains(element)))) {
    signal.throwIfAborted();
    const rect = element.getBoundingClientRect();
    if (!rect.width || !rect.height) continue;
    if (rect.width * scale > 8192 || rect.height * scale > 8192 || Math.ceil(rect.width * scale) * Math.ceil(rect.height * scale) > 16_777_216) throw Error('渐变文字尺寸超出图片导出支持范围');
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('width', String(rect.width * scale));
    svg.setAttribute('height', String(rect.height * scale));
    svg.setAttribute('viewBox', `0 0 ${rect.width} ${rect.height}`);
    const foreign = document.createElementNS(svg.namespaceURI, 'foreignObject');
    foreign.setAttribute('width', String(rect.width));
    foreign.setAttribute('height', String(rect.height));
    const wrapper = document.createElement('div');
    const rules = document.createElement('style');
    rules.textContent = pseudoStyles;
    const copy = element.cloneNode(true) as HTMLElement;
    const originals = [element,...element.querySelectorAll<HTMLElement>('*')];
    const copies = [copy,...copy.querySelectorAll<HTMLElement>('*')];
    for(let index=0;index<originals.length;index++)copies[index].style.cssText=computedDeclarations(getComputedStyle(originals[index]));
    copy.style.margin = '0';
    copy.style.position = 'static';
    copy.style.transform = 'none';
    copy.style.width = `${rect.width}px`;
    copy.style.height = `${rect.height}px`;
    wrapper.append(rules, copy);
    foreign.append(wrapper);
    svg.append(foreign);
    const image = document.createElement('img');
    image.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(new XMLSerializer().serializeToString(svg));
    await abortable(image.decode(), signal);
    signal.throwIfAborted();
    const canvas = document.createElement('canvas');
    canvas.width = Math.ceil(rect.width * scale);
    canvas.height = Math.ceil(rect.height * scale);
    const context = canvas.getContext('2d');
    if (!context) throw new Error('无法绘制渐变文字');
    let url: string;
    try {
      context.drawImage(image, 0, 0);
      const blob = await new Promise<Blob>((resolve,reject) => canvas.toBlob(value => value ? resolve(value) : reject(Error('渐变文字编码失败')),'image/png'));
      url = URL.createObjectURL(blob);
      signal.throwIfAborted();
    } finally { canvas.width = 0; canvas.height = 0; }
    element.style.position = 'relative';
    element.style.backgroundImage = 'none';
    element.style.color = 'transparent';
    element.style.setProperty('-webkit-text-fill-color', 'transparent');
    for (const child of element.querySelectorAll<HTMLElement>('*')) child.style.visibility = 'hidden';
    if (element.dataset.pdfElement !== undefined) {
      const hide = document.createElement('style');
      hide.textContent = `[data-pdf-element="${element.dataset.pdfElement}"]::before,[data-pdf-element="${element.dataset.pdfElement}"]::after{content:none!important}`;
      view.append(hide);
    }
    const frozen = document.createElement('img');
    frozen.src = url;
    frozen.alt = element.textContent ?? '';
    frozen.dataset.pdfGradientText = '';
    frozen.style.cssText = `position:absolute;left:0;top:0;width:${rect.width}px;height:${rect.height}px;max-width:none;visibility:visible;`;
    element.append(frozen);
    await abortable(frozen.decode(), signal);
  }
}

export function abortable<T>(work: Promise<T>, signal: AbortSignal): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const abort = () => reject(signal.reason ?? new DOMException('PDF 导出已取消', 'AbortError'));
    signal.addEventListener('abort', abort, { once: true });
    if (signal.aborted) abort();
    work.then(resolve, reject).finally(() => signal.removeEventListener('abort', abort));
  });
}
